import os
import sys
import glob
import uuid
from pathlib import Path

# Ensure UTF-8 output on Windows console
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

from config import setup_global_settings, get_neo4j_driver
from utils import chunk_markdown

def extract_category_from_path(filepath, base_dir="markdown_output"):
    """Derives a hierarchical category name from the parent directory relative to markdown_output."""
    path_obj = Path(filepath)
    parts = path_obj.parts
    try:
        base_idx = parts.index(base_dir)
        # Take subfolder path if available (e.g. "Finance/2024" or "Policies")
        rel_parts = parts[base_idx + 1:-1]
        if rel_parts:
            # If the last folder is just the document folder generated by Marker, exclude it
            doc_folder = path_obj.parent.name
            if doc_folder == path_obj.stem and len(rel_parts) > 1:
                rel_parts = rel_parts[:-1]
            category = " / ".join(rel_parts)
            return category
    except ValueError:
        pass
    return "General"

def build_knowledge_graph():
    """Reads Markdown documents, chunks them with table-awareness,
    generates dense embeddings, and builds a Knowledge Graph in Neo4j.
    """
    print("Setting up global LLM and embedding settings...")
    llm = setup_global_settings()

    from llama_index.core.embeddings.utils import resolve_embed_model
    from llama_index.core import Settings
    embed_model = resolve_embed_model(Settings.embed_model)
    print(f"Embedding model loaded: {embed_model.model_name}")

    input_dir = "markdown_output"
    if not os.path.exists(input_dir) or not os.listdir(input_dir):
        print(f"Error: '{input_dir}' is empty or does not exist. Please run '1_convert_documents.py' first or place markdown files in '{input_dir}'.")
        return

    # Find all markdown files recursively
    md_files = glob.glob(os.path.join(input_dir, "**", "*.md"), recursive=True)
    if not md_files:
        print(f"No markdown files found in '{input_dir}'.")
        return
        
    print(f"Found {len(md_files)} markdown files to index.")

    # 1. Reset database
    print("Resetting Neo4j database...")
    driver = get_neo4j_driver()
    with driver.session() as session:
        session.run("MATCH (n) DETACH DELETE n")
        # Drop existing indexes to avoid conflicts
        try:
            session.run("DROP INDEX chunk_text_index IF EXISTS")
        except Exception:
            pass
        try:
            session.run("DROP INDEX chunk_vector_index IF EXISTS")
        except Exception:
            pass
    print("Database cleared.")

    # 2. Parse all documents into chunks
    all_chunks = []
    print("Parsing documents into table-aware chunks...")
    for filepath in md_files:
        path_obj = Path(filepath)
        filename = path_obj.stem
        category = extract_category_from_path(filepath, input_dir)
        
        print(f"  - Document: '{filename}' | Category: '{category}'")
        
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                content = f.read()
        except Exception as e:
            print(f"    Failed to read: {e}")
            continue
            
        chunks = chunk_markdown(content, max_chunk_size=1000, doc_name=filename, category=category)
        print(f"    -> {len(chunks)} chunks.")
        
        doc_id = str(uuid.uuid4())
        for idx, chunk in enumerate(chunks):
            chunk["category"] = category
            chunk["document_name"] = filename
            chunk["doc_id"] = doc_id
            chunk["chunk_id"] = str(uuid.uuid4())
            chunk["chunk_index"] = idx
            all_chunks.append(chunk)
            
    if not all_chunks:
        print("No chunks parsed from documents. Exiting.")
        return
        
    print(f"\nTotal chunks parsed across all documents: {len(all_chunks)}")

    # 3. Generate embeddings in batches
    print("Generating dense embeddings...")
    batch_size = 32
    texts = [c["text"] for c in all_chunks]
    all_embeddings = []
    for i in range(0, len(texts), batch_size):
        batch = texts[i:i+batch_size]
        embeddings = embed_model.get_text_embedding_batch(batch)
        all_embeddings.extend(embeddings)
        print(f"  Embedded {min(i+batch_size, len(texts))}/{len(texts)} chunks")
    
    print("Embeddings generated successfully!")

    # 4. Insert chunks into Neo4j directly
    print("Inserting chunks into Neo4j...")
    with driver.session() as session:
        for i, chunk in enumerate(all_chunks):
            session.run("""
                 CREATE (c:Chunk {
                    id: $id,
                    text: $text,
                    chunk_type: $chunk_type,
                    header_path: $header_path,
                    category: $category,
                    document_name: $document_name,
                    doc_id: $doc_id,
                    chunk_index: $chunk_index,
                    embedding: $embedding
                })
            """, {
                "id": chunk["chunk_id"],
                "text": chunk["text"],
                "chunk_type": chunk["type"],
                "header_path": chunk["header_path"],
                "category": chunk["category"],
                "document_name": chunk["document_name"],
                "doc_id": chunk["doc_id"],
                "chunk_index": chunk["chunk_index"],
                "embedding": all_embeddings[i]
            })
            
            if (i + 1) % 50 == 0 or i == len(all_chunks) - 1:
                print(f"  Inserted {i+1}/{len(all_chunks)} chunks")
    
    print("All chunks inserted!")

    # 5. Create structured metadata nodes and relationships
    print("Creating structured metadata graph topology...")
    with driver.session() as session:
        # Document nodes
        print("  - Creating Document nodes...")
        session.run("""
            MATCH (c:Chunk)
            WITH DISTINCT c.document_name AS name, c.doc_id AS doc_id, c.category AS category
            MERGE (d:Document {name: name})
            ON CREATE SET d.id = doc_id, d.category = category
        """)
        
        # Link Documents -> Chunks
        print("  - Linking Documents to Chunks (HAS_CHUNK)...")
        session.run("""
            MATCH (c:Chunk), (d:Document {name: c.document_name})
            MERGE (d)-[:HAS_CHUNK]->(c)
        """)
        
        # Link sequential chunks within the same document (NEXT)
        print("  - Linking sequential chunks (NEXT)...")
        session.run("""
            MATCH (d:Document)-[:HAS_CHUNK]->(c1:Chunk)
            MATCH (d)-[:HAS_CHUNK]->(c2:Chunk)
            WHERE c1.chunk_index + 1 = c2.chunk_index
            MERGE (c1)-[:NEXT]->(c2)
        """)
        
        # Category nodes
        print("  - Creating Category nodes & links...")
        session.run("""
            MATCH (d:Document)
            WHERE d.category IS NOT NULL AND d.category <> 'General'
            MERGE (cat:Category {name: d.category})
            MERGE (d)-[:IN_CATEGORY]->(cat)
            MERGE (cat)-[:HAS_DOCUMENT]->(d)
        """)
        
        # Full-text index (Lucene BM25)
        print("  - Creating full-text index (chunk_text_index)...")
        session.run("""
            CREATE FULLTEXT INDEX chunk_text_index IF NOT EXISTS
            FOR (n:Chunk)
            ON EACH [n.text]
        """)
        
        # Vector index (Cosine similarity)
        print("  - Creating vector index (chunk_vector_index)...")
        session.run("""
            CREATE VECTOR INDEX chunk_vector_index IF NOT EXISTS
            FOR (n:Chunk)
            ON (n.embedding)
            OPTIONS {indexConfig: {
                `vector.dimensions`: 384,
                `vector.similarity_function`: 'cosine'
            }}
        """)

    print("\n=== Knowledge Graph building completed successfully! ===")
    
    # 6. Verify and output summary
    with driver.session() as session:
        result = session.run("MATCH (c:Chunk) RETURN count(c) as cnt").single()
        print(f"  Chunks indexed: {result['cnt']}")
        result = session.run("MATCH (d:Document) RETURN count(d) as cnt").single()
        print(f"  Documents indexed: {result['cnt']}")
        result = session.run("MATCH (cat:Category) RETURN count(cat) as cnt").single()
        print(f"  Categories created: {result['cnt']}")
        
        print("\n  Document summary:")
        results = session.run("MATCH (d:Document) RETURN d.name as name, d.category as category")
        for r in results:
            print(f"    - {r['name']} | Category: {r['category']}")

    driver.close()

if __name__ == "__main__":
    build_knowledge_graph()
